class StatefulConstrainedDecodingError(RuntimeError):
    """Stable fail-closed error raised by the constrained decoder."""

    def __init__(self, code: str, message: str) -> None:
        if code not in _SAFE_ERROR_CODES:
            raise ValueError("unknown constrained-decoding error code")
        super().__init__(message)
        self.code = code


class _PrefixRejected(ValueError):
    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


@dataclass(frozen=True)
class ConstraintLimits:
    """Hard complexity limits for one candidate."""

    max_sections: int = 8
    max_components: int = 32
    max_states: int = 16
    max_interactions: int = 24
    max_acceptance_checks: int = 16
    max_stable_id_chars: int = 96
    max_text_chars: int = 512
    max_generated_tokens: int = 8192
    max_token_piece_chars: int = 48
    max_elapsed_seconds: float = 3600.0

    def validate(self) -> None:
        values = (
            self.max_sections,
            self.max_components,
            self.max_states,
            self.max_interactions,
            self.max_acceptance_checks,
            self.max_stable_id_chars,
            self.max_text_chars,
            self.max_generated_tokens,
            self.max_token_piece_chars,
        )
        if any(type(value) is not int or value <= 0 for value in values):
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "constraint limits must be positive integers"
            )
        if self.max_sections > 32:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "section limit exceeds the treatment cap"
            )
        if self.max_components > 128:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "component limit exceeds the treatment cap"
            )
        if self.max_states < 2 or self.max_states > 64:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "state limit is outside the treatment range"
            )
        if self.max_interactions > 128 or self.max_acceptance_checks > 64:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "relation limit exceeds the treatment cap"
            )
        if self.max_stable_id_chars > 96 or self.max_text_chars > 2048:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "string limit exceeds the strict contract cap"
            )
        if self.max_generated_tokens > 32768 or self.max_token_piece_chars > 128:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "token limit exceeds the treatment cap"
            )
        if (
            isinstance(self.max_elapsed_seconds, bool)
            or not isinstance(self.max_elapsed_seconds, (int, float))
            or not math.isfinite(self.max_elapsed_seconds)
            or self.max_elapsed_seconds <= 0
            or self.max_elapsed_seconds > 86400
        ):
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "elapsed-time cap is invalid"
            )


