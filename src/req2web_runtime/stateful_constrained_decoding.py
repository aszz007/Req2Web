"""Local-only stateful constrained decoding for one semantic-candidate call.

The controller in this module is deliberately narrower than a general JSON
grammar.  It fixes the versioned semantic-candidate shape, lets the model
declare bounded semantic entities, and constrains later references to the
resulting symbol table.  It never edits generated bytes and it does not create
components, states, interactions, or acceptance checks on the model's behalf.

The public callback is compatible with Transformers'
``prefix_allowed_tokens_fn`` for batch size one, greedy decoding, and one beam.
This is an experimental optional spike module; it is not wired into the default
Provider or trusted-remote executor and is not a production routing path.
"""

