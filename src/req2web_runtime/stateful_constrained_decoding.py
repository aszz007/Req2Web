class _TokenizerVocabulary:
    def __init__(
        self,
        tokenizer: object,
        limits: ConstraintLimits,
        generation_eos_token_id: int,
        model_vocabulary_size: int,
    ) -> None:
        self.tokenizer = tokenizer
        self.generation_eos_token_id = generation_eos_token_id
        self.model_vocabulary_size = model_vocabulary_size
        token_ids = [
            item
            for item in self._token_ids(tokenizer)
            if item < model_vocabulary_size
        ]
        self.token_ids = tuple(token_ids)
        special_ids = {
            int(item)
            for item in getattr(tokenizer, "all_special_ids", ())
            if type(item) is int and 0 <= item < model_vocabulary_size
        }
        self.id_to_piece: dict[int, str] = {}
        self.exact_piece_ids: dict[str, list[int]] = {}
        self.text_piece_ids_by_length: dict[int, list[int]] = {}
        self.text_initial_piece_ids_by_length: dict[int, list[int]] = {}
        self.stable_initial_piece_ids_by_length: dict[int, list[int]] = {}
        self.stable_continue_piece_ids_by_length: dict[int, list[int]] = {}
        decodable_ids = [
            item
            for item in self.token_ids
            if item != generation_eos_token_id and item not in special_ids
        ]
        for token_id, piece in zip(
            decodable_ids, self._batch_decode(tokenizer, decodable_ids)
        ):
            if not isinstance(piece, str) or not piece:
                continue
            self.id_to_piece[token_id] = piece
            self.exact_piece_ids.setdefault(piece, []).append(token_id)
            length = len(piece)
            if length > limits.max_token_piece_chars:
                continue
            if all(
                ord(character) >= 0x20 and character not in {'"', "\\"}
                for character in piece
            ):
                self.text_piece_ids_by_length.setdefault(length, []).append(token_id)
                if not piece[0].isspace():
                    self.text_initial_piece_ids_by_length.setdefault(
                        length, []
                    ).append(token_id)
            if piece[0] in _STABLE_ID_FIRST and all(
                character in _STABLE_ID_REST for character in piece[1:]
            ):
                self.stable_initial_piece_ids_by_length.setdefault(
                    length, []
                ).append(token_id)
            if all(character in _STABLE_ID_REST for character in piece):
                self.stable_continue_piece_ids_by_length.setdefault(
                    length, []
                ).append(token_id)
        self._max_piece_length = limits.max_token_piece_chars
        self._cache: dict[tuple[str, int], tuple[int, ...]] = {}

    @staticmethod
    def _token_ids(tokenizer: object) -> list[int]:
        getter = getattr(tokenizer, "get_vocab", None)
        if callable(getter):
            vocabulary = getter()
            if not isinstance(vocabulary, Mapping):
                raise StatefulConstrainedDecodingError(
                    "tokenizer_incompatible", "tokenizer vocabulary is invalid"
                )
            ids = sorted(
                {
                    int(value)
                    for value in vocabulary.values()
                    if type(value) is int and value >= 0
                }
            )
            if ids:
                return ids
        try:
            length = len(tokenizer)  # type: ignore[arg-type]
        except (TypeError, AttributeError) as exc:
            raise StatefulConstrainedDecodingError(
                "tokenizer_incompatible", "tokenizer has no enumerable vocabulary"
            ) from exc
        if type(length) is not int or length <= 0:
            raise StatefulConstrainedDecodingError(
                "tokenizer_incompatible", "tokenizer vocabulary is empty"
            )
        return list(range(length))

    @staticmethod
    def _batch_decode(tokenizer: object, token_ids: Sequence[int]) -> list[str]:
        decoder = getattr(tokenizer, "batch_decode", None)
        if callable(decoder):
            result: list[str] = []
            for start in range(0, len(token_ids), 4096):
                batch = [[item] for item in token_ids[start : start + 4096]]
                try:
                    values = decoder(
                        batch,
                        skip_special_tokens=False,
                        clean_up_tokenization_spaces=False,
                    )
                except TypeError:
                    values = decoder(batch, skip_special_tokens=False)
                if not isinstance(values, list) or len(values) != len(batch):
                    raise StatefulConstrainedDecodingError(
                        "tokenizer_incompatible",
                        "tokenizer batch decoding is inconsistent",
                    )
                result.extend(str(item) for item in values)
            return result
        single = getattr(tokenizer, "decode", None)
        if not callable(single):
            raise StatefulConstrainedDecodingError(
                "tokenizer_incompatible", "tokenizer has no decode interface"
            )
        result = []
        for token_id in token_ids:
            try:
                piece = single(
                    [token_id],
                    skip_special_tokens=False,
                    clean_up_tokenization_spaces=False,
                )
            except TypeError:
                piece = single([token_id], skip_special_tokens=False)
            result.append(str(piece))
        return result

    def decode_ids(self, token_ids: Sequence[int]) -> str:
        decoder = getattr(self.tokenizer, "decode", None)
        if not callable(decoder):
            raise StatefulConstrainedDecodingError(
                "tokenizer_incompatible", "tokenizer has no decode interface"
            )
        try:
            value = decoder(
                list(token_ids),
                skip_special_tokens=False,
                clean_up_tokenization_spaces=False,
            )
        except TypeError:
            value = decoder(list(token_ids), skip_special_tokens=False)
        if not isinstance(value, str):
            raise StatefulConstrainedDecodingError(
                "tokenizer_incompatible", "tokenizer decode result is not text"
            )
        return value

    def exact(self, value: str) -> tuple[int, ...]:
        return tuple(self.exact_piece_ids.get(value, ()))

    def prefix_tokens(self, suffix: str) -> tuple[int, ...]:
        result: list[int] = []
        upper = min(len(suffix), self._max_piece_length)
        for length in range(1, upper + 1):
            result.extend(self.exact_piece_ids.get(suffix[:length], ()))
        return tuple(result)

    def _bounded(
        self,
        key: str,
        groups: Mapping[int, list[int]],
        remaining: int,
    ) -> tuple[int, ...]:
        bounded = min(remaining, self._max_piece_length)
        cache_key = (key, bounded)
        cached = self._cache.get(cache_key)
        if cached is not None:
            return cached
        result: list[int] = []
        for length in range(1, bounded + 1):
            result.extend(groups.get(length, ()))
        value = tuple(result)
        self._cache[cache_key] = value
        return value

    def text_tokens(self, remaining: int, *, initial: bool) -> tuple[int, ...]:
        groups = (
            self.text_initial_piece_ids_by_length
            if initial
            else self.text_piece_ids_by_length
        )
        return self._bounded("text_initial" if initial else "text", groups, remaining)

    def stable_tokens(self, remaining: int, *, initial: bool) -> tuple[int, ...]:
        groups = (
            self.stable_initial_piece_ids_by_length
            if initial
            else self.stable_continue_piece_ids_by_length
        )
        return self._bounded(
            "stable_initial" if initial else "stable", groups, remaining
        )


class StatefulConstrainedGeneration:
    """One-call stateful constraint controller for a semantic candidate."""

    def __init__(
        self,
        tokenizer: object,
        prompt_token_length: int,
        approved_use_case_ids: Sequence[str],
        *,
        generation_eos_token_id: int,
        model_vocabulary_size: int,
        limits: ConstraintLimits | None = None,
        batch_size: int = 1,
        num_beams: int = 1,
        do_sample: bool = False,
        num_return_sequences: int = 1,
    ) -> None:
        self.limits = limits or ConstraintLimits()
        self.limits.validate()
        if type(prompt_token_length) is not int or prompt_token_length <= 0:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "prompt token length must be positive"
            )
        if type(model_vocabulary_size) is not int or model_vocabulary_size <= 0:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "model vocabulary size must be positive"
            )
        if (
            type(generation_eos_token_id) is not int
            or generation_eos_token_id < 0
            or generation_eos_token_id >= model_vocabulary_size
        ):
            raise StatefulConstrainedDecodingError(
                "invalid_configuration",
                "generation EOS token must be inside the model vocabulary",
            )
        if type(batch_size) is not int or batch_size != 1:
            raise StatefulConstrainedDecodingError(
                "unsupported_batch", "stateful decoding supports batch size one"
            )
        if type(num_beams) is not int or num_beams != 1:
            raise StatefulConstrainedDecodingError(
                "unsupported_beam", "stateful decoding supports one greedy beam"
            )
        if type(do_sample) is not bool or do_sample:
            raise StatefulConstrainedDecodingError(
                "unsupported_sampling", "stateful decoding requires greedy sampling"
            )
        if type(num_return_sequences) is not int or num_return_sequences != 1:
            raise StatefulConstrainedDecodingError(
                "unsupported_beam", "stateful decoding supports one return sequence"
            )
        use_case_ids = tuple(approved_use_case_ids)
        if not 2 <= len(use_case_ids) <= 4:
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "exactly two to four use cases are required"
            )
        if any(
            not isinstance(item, str)
            or not item
            or item != item.strip()
            or len(item) > 128
            for item in use_case_ids
        ):
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "approved use-case IDs are invalid"
            )
        if len(use_case_ids) != len(set(use_case_ids)):
            raise StatefulConstrainedDecodingError(
                "invalid_configuration", "approved use-case IDs must be unique"
            )
        self.prompt_token_length = prompt_token_length
        self.approved_use_case_ids = use_case_ids
        self.generation_eos_token_id = generation_eos_token_id
        self.model_vocabulary_size = model_vocabulary_size
        self._vocabulary = _TokenizerVocabulary(
            tokenizer,
            self.limits,
            generation_eos_token_id,
            model_vocabulary_size,
        )
        self._machine = _SemanticCandidateMachine(use_case_ids, self.limits)
        self._prompt_token_ids: tuple[int, ...] | None = None
        self._raw_token_ids: tuple[int, ...] = ()
        self._generated_token_ids: tuple[int, ...] = ()
        self._last_allowed: tuple[int, ...] | None = None
        self._last_allowed_prefix: tuple[int, ...] | None = None
        self._callback_count = 0
        self._mask_compute_count = 0
        self._allowed_observations = 0
        self._masked_observations = 0
        self._rejection_counts: dict[str, int] = {}
        self._forced_token_positions: list[ForcedTokenPosition] = []
        self._failed_code = ""
        self._finalized = False
        self._completion: StatefulConstrainedGenerationCompletion | None = None
        self._started_at = time.monotonic()

    @property
    def generated_token_ids(self) -> tuple[int, ...]:
        return self._generated_token_ids

    @property
    def raw_token_ids(self) -> tuple[int, ...]:
        return self._raw_token_ids

    @property
    def is_complete(self) -> bool:
        return self._finalized

    def _fail(self, code: str, message: str) -> None:
        if not self._failed_code:
            self._failed_code = code
        raise StatefulConstrainedDecodingError(self._failed_code, message)

    def _check_elapsed(self) -> None:
        if time.monotonic() - self._started_at > self.limits.max_elapsed_seconds:
            self._fail(
                "resource_cap_exceeded", "generation elapsed time exceeds the hard cap"
            )

    @staticmethod
    def _ids(value: object) -> tuple[int, ...]:
        converter = getattr(value, "tolist", None)
        if callable(converter):
            value = converter()
        if not isinstance(value, (list, tuple)):
            raise StatefulConstrainedDecodingError(
                "unsupported_batch", "input_ids must be one-dimensional"
            )
        if value and isinstance(value[0], (list, tuple)):
            raise StatefulConstrainedDecodingError(
                "unsupported_batch", "input_ids must be one-dimensional"
            )
        result: list[int] = []
        for item in value:
            if type(item) is not int or item < 0:
                raise StatefulConstrainedDecodingError(
                    "invalid_configuration", "input_ids contain an invalid token ID"
                )
            result.append(item)
        return tuple(result)

    def _observe_prefix(self, input_ids: object) -> None:
        ids = self._ids(input_ids)
        if any(item >= self.model_vocabulary_size for item in ids):
            self._fail(
                "invalid_configuration",
                "input_ids contain a token outside the model vocabulary",
            )
        if self._prompt_token_ids is None:
            if len(ids) != self.prompt_token_length:
                self._fail(
                    "prefix_divergence",
                    "the first callback must receive the exact prompt length",
                )
            self._prompt_token_ids = ids
            self._last_allowed_prefix = ()
            return
        if len(ids) < self.prompt_token_length:
            self._fail("prefix_divergence", "the captured prompt prefix was truncated")
        if ids[: self.prompt_token_length] != self._prompt_token_ids:
            self._fail("prefix_divergence", "the captured prompt prefix changed")
        generated = ids[self.prompt_token_length :]
        if generated == self._raw_token_ids:
            return
        if (
            len(generated) != len(self._raw_token_ids) + 1
            or generated[:-1] != self._raw_token_ids
        ):
            self._fail(
                "prefix_divergence",
                "generation prefix is not one greedy continuation",
            )
        selected = generated[-1]
        if self._last_allowed is None or selected not in self._last_allowed:
            self._fail(
                "prefix_divergence",
                "generation selected a token outside the preceding mask",
            )
        if selected == self.generation_eos_token_id:
            self._fail(
                "controller_closed",
                "EOS must be consumed only by finalize after complete JSON",
            )
        if len(generated) > self.limits.max_generated_tokens:
            self._fail(
                "resource_cap_exceeded", "generated token count exceeds the hard cap"
            )
        piece = self._vocabulary.id_to_piece.get(selected)
        if piece is None:
            self._fail(
                "tokenizer_incompatible", "selected token has no stable decoded piece"
            )
        task = self._machine.current_task
        forced_reason = ""
        if task is not None:
            if task.kind == "literal":
                forced_reason = task.mask_code
            elif task.kind == "boundary" and len(task.options) == 1:
                forced_reason = task.mask_code
            elif task.kind == "choice":
                viable = [
                    option
                    for option in task.options
                    if option.startswith(task.value)
                ]
                if len(viable) == 1:
                    forced_reason = task.mask_code
            elif task.kind in {"text", "stable_id"} and piece == '"':
                forced_reason = "json_string_boundary"
        if forced_reason:
            self._forced_token_positions.append(
                ForcedTokenPosition(
                    generated_position=len(generated),
                    token_id=selected,
                    reason=forced_reason,
                )
            )
        try:
            self._machine.feed(piece)
        except _PrefixRejected as exc:
            self._fail(
                "parser_state_drift",
                f"selected token diverged from parser state: {exc.code}",
            )
        self._raw_token_ids = generated
        self._generated_token_ids = generated
        replay = "".join(
            self._vocabulary.id_to_piece[item] for item in self._raw_token_ids
        )
        decoded = self._vocabulary.decode_ids(self._raw_token_ids)
        if decoded != replay:
            self._fail(
                "parser_state_drift",
                "tokenizer sequence decoding is not compositional for selected tokens",
            )
        self._last_allowed_prefix = None

    def _allowed_for_task(self) -> tuple[int, ...]:
        if self._machine.complete:
            return (self.generation_eos_token_id,)
        task = self._machine.current_task
        assert task is not None
        if task.kind == "literal":
            return self._vocabulary.prefix_tokens(task.literal[task.position :])
        if task.kind in {"choice", "boundary"}:
            allowed: set[int] = set()
            for option in task.options:
                if not option.startswith(task.value):
                    continue
                suffix = option[len(task.value) :]
                allowed.update(self._vocabulary.prefix_tokens(suffix))
            return tuple(sorted(allowed))
        if task.kind in {"text", "stable_id"}:
            if not task.opened:
                return self._vocabulary.exact('"')
            if task.kind == "text":
                remaining = task.max_length - len(task.decoded_value)
                if task.escape_state == "escape":
                    escape_characters = tuple(_JSON_SIMPLE_ESCAPES) + ("u",)
                    if not task.decoded_value:
                        escape_characters = tuple(
                            item
                            for item in escape_characters
                            if item == "u"
                            or not _JSON_SIMPLE_ESCAPES.get(item, "").isspace()
                        )
                    allowed: set[int] = set()
                    for character in escape_characters:
                        allowed.update(self._vocabulary.exact(character))
                    return tuple(sorted(allowed))
                if task.escape_state == "unicode":
                    digits = _JSON_HEX_DIGITS
                    if (
                        len(task.unicode_digits) == 3
                        and not task.decoded_value
                    ):
                        digits = frozenset(
                            character
                            for character in digits
                            if not chr(
                                int(task.unicode_digits + character, 16)
                            ).isspace()
                        )
                    allowed = set()
                    for character in digits:
                        allowed.update(self._vocabulary.exact(character))
                    return tuple(sorted(allowed))
                values = self._vocabulary.text_tokens(
                    remaining, initial=not task.decoded_value
                )
                if remaining > 0:
                    values = (*values, *self._vocabulary.exact("\\"))
            else:
                remaining = task.max_length - len(task.value)
                values = self._vocabulary.stable_tokens(
                    remaining, initial=not task.value
                )
            if self._machine.can_close_string(task):
                return (*values, *self._vocabulary.exact('"'))
            return values
        self._fail("parser_state_drift", "unknown constrained parser task")
        raise AssertionError("unreachable")

    def prefix_allowed_tokens_fn(
        self, batch_id: int, input_ids: object
    ) -> list[int]:
        """Transformers-compatible greedy prefix mask."""

        if self._finalized:
            self._fail("controller_closed", "constrained generation is finalized")
        if self._failed_code:
            self._fail(self._failed_code, "constrained generation already failed")
        if type(batch_id) is not int or batch_id != 0:
            self._fail(
                "unsupported_batch", "stateful decoding supports only batch index zero"
            )
        self._check_elapsed()
        self._callback_count += 1
        self._observe_prefix(input_ids)
        if (
            self._last_allowed is not None
            and self._last_allowed_prefix == self._raw_token_ids
        ):
            return list(self._last_allowed)
        allowed = self._allowed_for_task()
        if not allowed:
            self._fail("no_legal_token", "no tokenizer token satisfies the next state")
        if any(
            type(token_id) is not int
            or token_id < 0
            or token_id >= self.model_vocabulary_size
            for token_id in allowed
        ):
            self._fail(
                "parser_state_drift",
                "constraint mask contains a token outside the model vocabulary",
            )
        self._mask_compute_count += 1
        self._allowed_observations += len(allowed)
        masked = self.model_vocabulary_size - len(set(allowed))
        self._masked_observations += masked
        task = self._machine.current_task
        mask_code = "complete_eos_only" if task is None else task.mask_code
        self._rejection_counts[mask_code] = (
            self._rejection_counts.get(mask_code, 0) + masked
        )
        self._last_allowed = allowed
        self._last_allowed_prefix = self._raw_token_ids
        return list(allowed)

    def replay_raw_bytes(self) -> bytes:
        """Return the exact token replay bytes without repair or normalization."""

        if not self._raw_token_ids:
            return b""
        decoded = self._vocabulary.decode_ids(self._raw_token_ids)
        replay = "".join(
            self._vocabulary.id_to_piece[item] for item in self._raw_token_ids
        )
        if decoded != replay:
            self._fail(
                "parser_state_drift", "raw token replay changed decoded text"
            )
        return decoded.encode("utf-8")

    def audit_summary(self) -> StatefulConstraintAuditSummary:
        raw = b""
        raw_unmodified = False
        if self._raw_token_ids and not self._failed_code:
            try:
                raw = self.replay_raw_bytes()
                raw_unmodified = self._finalized
            except StatefulConstrainedDecodingError:
                raw = b""
        status = (
            "failed"
            if self._failed_code
            else "complete"
            if self._finalized
            else "active"
        )
        return StatefulConstraintAuditSummary(
            schema_version=STATEFUL_CONSTRAINED_DECODING_AUDIT_SCHEMA_VERSION,
            treatment_id=STATEFUL_CONSTRAINED_GENERATION_TREATMENT_ID,
            treatment_version=STATEFUL_CONSTRAINED_GENERATION_TREATMENT_VERSION,
            status=status,
            execution_profile="local_smoke",
            success_interpretation="stateful_constrained_generation_only",
            unconstrained_first_pass_model_success_claimed=False,
            formal_quality_claimed=False,
            h1_or_gold_used=False,
            raw_repair_performed=False,
            approved_use_case_ids=self.approved_use_case_ids,
            model_owned_fields=_MODEL_OWNED_FIELDS,
            constraint_owned_fields=_CONSTRAINT_OWNED_FIELDS,
            forced_token_positions=tuple(self._forced_token_positions),
            symbol_table_transitions=tuple(self._machine.transitions),
            callback_count=self._callback_count,
            mask_compute_count=self._mask_compute_count,
            model_vocabulary_size=self.model_vocabulary_size,
            allowed_token_observations=self._allowed_observations,
            masked_token_observations=self._masked_observations,
            elapsed_milliseconds=max(
                0, int((time.monotonic() - self._started_at) * 1000)
            ),
            rejection_counts=tuple(sorted(self._rejection_counts.items())),
            generated_token_ids=self._generated_token_ids,
            raw_token_ids=self._raw_token_ids,
            generation_eos_token_id=self.generation_eos_token_id,
            complete=self._finalized,
            raw_unmodified=raw_unmodified,
            raw_byte_length=len(raw),
            raw_sha256=hashlib.sha256(raw).hexdigest() if raw else "",
            error_code=self._failed_code,
        )

    def finalize(
        self, output_ids: object
    ) -> StatefulConstrainedGenerationCompletion:
        """Finalize exactly one complete raw JSON followed by EOS."""

        if self._completion is not None:
            return self._completion
        if self._failed_code:
            self._fail(self._failed_code, "constrained generation already failed")
        self._check_elapsed()
        if self._prompt_token_ids is None:
            self._fail(
                "incomplete_generation", "prefix callback was never initialized"
            )
        ids = self._ids(output_ids)
        if any(item >= self.model_vocabulary_size for item in ids):
            self._fail(
                "invalid_configuration",
                "final output contains a token outside the model vocabulary",
            )
        if (
            len(ids) < self.prompt_token_length
            or ids[: self.prompt_token_length] != self._prompt_token_ids
        ):
            self._fail("prefix_divergence", "final output prompt binding changed")
        generated = ids[self.prompt_token_length :]
        expected = (*self._raw_token_ids, self.generation_eos_token_id)
        if generated != expected:
            self._fail(
                "incomplete_generation",
                "final output must be the observed complete JSON followed by EOS",
            )
        if not self._machine.complete:
            self._fail(
                "incomplete_generation", "semantic-candidate JSON is incomplete"
            )
        if self._last_allowed != (self.generation_eos_token_id,):
            self._fail(
                "incomplete_generation",
                "EOS was not independently exposed after complete JSON",
            )
        raw = self.replay_raw_bytes()
        try:
            candidate = parse_provider_raw_response(
                ProviderRawResponse.from_bytes(raw)
            )
        except (TypeError, ValueError) as exc:
            self._fail(
                "invalid_completion",
                "complete bytes failed the unchanged strict semantic-candidate parser",
            )
            raise AssertionError("unreachable") from exc
        if {
            item.use_case_id for item in candidate.use_case_mappings
        } != set(self.approved_use_case_ids):
            self._fail(
                "invalid_completion",
                "complete candidate does not bind the approved use cases",
            )
        if any(
            item.source_state_stable_id == item.target_state_stable_id
            for item in candidate.interactions
        ):
            self._fail(
                "invalid_completion", "complete candidate contains a self-loop"
            )
        self._generated_token_ids = generated
        self._finalized = True
        audit = self.audit_summary()
        completion = StatefulConstrainedGenerationCompletion(
            schema_version=STATEFUL_CONSTRAINED_DECODING_COMPLETION_SCHEMA_VERSION,
            treatment_id=STATEFUL_CONSTRAINED_GENERATION_TREATMENT_ID,
            treatment_version=STATEFUL_CONSTRAINED_GENERATION_TREATMENT_VERSION,
            raw_bytes=raw,
            raw_token_ids=self._raw_token_ids,
            generated_token_ids=generated,
            raw_sha256=hashlib.sha256(raw).hexdigest(),
            candidate_sha256=candidate.sha256(),
            complete=True,
            raw_unmodified=True,
            audit=audit,
        )
        self._completion = completion
        return completion


def create_stateful_constrained_generation(
    tokenizer: object,
    prompt_token_length: int,
    approved_use_case_ids: Sequence[str],
    *,
    generation_eos_token_id: int,
    model_vocabulary_size: int,
    limits: ConstraintLimits | None = None,
    batch_size: int = 1,
    num_beams: int = 1,
    do_sample: bool = False,
    num_return_sequences: int = 1,
) -> StatefulConstrainedGeneration:
    """Create the approved local-only v1 treatment controller."""

    return StatefulConstrainedGeneration(
        tokenizer,
        prompt_token_length,
        approved_use_case_ids,
        generation_eos_token_id=generation_eos_token_id,
        model_vocabulary_size=model_vocabulary_size,
        limits=limits,
        batch_size=batch_size,
        num_beams=num_beams,
        do_sample=do_sample,
        num_return_sequences=num_return_sequences,
    )
