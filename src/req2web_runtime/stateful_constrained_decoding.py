@dataclass
class _Task:
    kind: str
    tag: str = ""
    literal: str = ""
    options: tuple[str, ...] = ()
    values: tuple[str, ...] = ()
    position: int = 0
    value: str = ""
    decoded_value: str = ""
    opened: bool = False
    escape_state: str = ""
    unicode_digits: str = ""
    min_length: int = 1
    max_length: int = 1
    mask_code: str = "json_shape"


def _json_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True, separators=(",", ":"))


def _literal(value: str, *, mask_code: str = "constraint_owned_literal") -> _Task:
    if not value:
        raise ValueError("literal task must not be empty")
    return _Task(kind="literal", literal=value, mask_code=mask_code)


def _text(
    tag: str,
    *,
    min_length: int,
    max_length: int,
    mask_code: str = "json_text_shape",
) -> _Task:
    return _Task(
        kind="text",
        tag=tag,
        min_length=min_length,
        max_length=max_length,
        mask_code=mask_code,
    )


def _stable_id(tag: str, *, max_length: int) -> _Task:
    return _Task(
        kind="stable_id",
        tag=tag,
        min_length=1,
        max_length=max_length,
        mask_code="stable_id_shape_or_duplicate",
    )


def _choice(
    tag: str,
    values: Iterable[str],
    *,
    mask_code: str,
    encoded: bool = False,
) -> _Task:
    raw_values = tuple(values)
    options = raw_values if encoded else tuple(_json_string(item) for item in raw_values)
    if not options:
        return _Task(
            kind="choice",
            tag=tag,
            options=(),
            values=(),
            mask_code=mask_code,
        )
    return _Task(
        kind="choice",
        tag=tag,
        options=options,
        values=raw_values,
        mask_code=mask_code,
    )


def _boundary(tag: str, values: Iterable[str], *, mask_code: str) -> _Task:
    choices = tuple(values)
    return _Task(
        kind="boundary",
        tag=tag,
        options=choices,
        values=choices,
        mask_code=mask_code,
    )


class _SemanticCandidateMachine:
    def __init__(
        self,
        approved_use_case_ids: tuple[str, ...],
        limits: ConstraintLimits,
    ) -> None:
        self.approved_use_case_ids = approved_use_case_ids
        self.limits = limits
        self.tasks: list[_Task] = [
            _literal(
                '{"schema_version":'
                + _json_string(MODEL_SEMANTIC_CANDIDATE_SCHEMA_VERSION)
                + ',"title":'
            ),
            _text("title", min_length=1, max_length=limits.max_text_chars),
        ]
        self.global_ids: set[str] = set()
        self.layout_section_ids: list[str] = []
        self.sections: list[dict[str, object]] = []
        self.component_owners: list[tuple[str, str]] = []
        self.states: list[str] = []
        self.interactions: list[dict[str, object]] = []
        self.acceptance_checks: list[dict[str, object]] = []
        self.current_section_index = -1
        self.current_section_components: list[str] = []
        self.current_section_use_cases: list[str] = []
        self.current_state_id = ""
        self.current_state_components: list[str] = []
        self.current_interaction: dict[str, object] = {}
        self.current_check: dict[str, object] = {}
        self.transitions: list[SymbolTableTransition] = []

    @property
    def complete(self) -> bool:
        return not self.tasks

    @property
    def current_task(self) -> _Task | None:
        return self.tasks[0] if self.tasks else None

    def _push(self, *tasks: _Task) -> None:
        self.tasks.extend(tasks)

    def _transition(
        self,
        event: str,
        symbol_kind: str,
        stable_id: str,
        relation: str,
    ) -> None:
        self.transitions.append(
            SymbolTableTransition(
                sequence=len(self.transitions) + 1,
                event=event,
                symbol_kind=symbol_kind,
                stable_id=stable_id,
                relation=relation,
            )
        )

    def _declare(self, kind: str, value: str, relation: str) -> None:
        if value in self.global_ids:
            raise _PrefixRejected("duplicate_stable_id")
        self.global_ids.add(value)
        self._transition("declared", kind, value, relation)

    def can_close_string(self, task: _Task) -> bool:
        if not task.opened:
            return False
        if task.kind == "text":
            return (
                not task.escape_state
                and len(task.decoded_value) >= task.min_length
                and task.decoded_value == task.decoded_value.strip()
            )
        if task.kind == "stable_id":
            return (
                len(task.value) >= task.min_length
                and task.value not in self.global_ids
            )
        return False

    @staticmethod
    def _append_decoded_text(task: _Task, character: str) -> None:
        if len(task.decoded_value) >= task.max_length:
            raise _PrefixRejected("string_length_cap")
        if not task.decoded_value and character.isspace():
            raise _PrefixRejected("text_leading_space")
        task.decoded_value += character

    def feed(self, piece: str) -> None:
        if not isinstance(piece, str) or not piece:
            raise _PrefixRejected("tokenizer_piece_invalid")
        for character in piece:
            if not self.tasks:
                raise _PrefixRejected("trailing_content")
            task = self.tasks[0]
            completed, value = self._consume(task, character)
            if completed:
                self.tasks.pop(0)
                self._on_complete(task, value)

    def _consume(self, task: _Task, character: str) -> tuple[bool, str]:
        if task.kind == "literal":
            if task.position >= len(task.literal) or task.literal[task.position] != character:
                raise _PrefixRejected("literal_mismatch")
            task.position += 1
            return task.position == len(task.literal), task.literal

        if task.kind in {"choice", "boundary"}:
            candidate = task.value + character
            viable = [option for option in task.options if option.startswith(candidate)]
            if not viable:
                raise _PrefixRejected(task.mask_code)
            task.value = candidate
            if candidate in task.options:
                index = task.options.index(candidate)
                if any(
                    option != candidate and option.startswith(candidate)
                    for option in task.options
                ):
                    return False, ""
                return True, task.values[index]
            return False, ""

        if task.kind not in {"text", "stable_id"}:
            raise _PrefixRejected("parser_state_invalid")
        if not task.opened:
            if character != '"':
                raise _PrefixRejected(task.mask_code)
            task.opened = True
            return False, ""
        if task.kind == "text":
            if task.escape_state == "escape":
                if len(task.value) >= task.max_length * 6:
                    raise _PrefixRejected("string_length_cap")
                task.value += character
                if character == "u":
                    task.escape_state = "unicode"
                    task.unicode_digits = ""
                    return False, ""
                decoded = _JSON_SIMPLE_ESCAPES.get(character)
                if decoded is None:
                    raise _PrefixRejected("json_escape_invalid")
                self._append_decoded_text(task, decoded)
                task.escape_state = ""
                return False, ""
            if task.escape_state == "unicode":
                if character not in _JSON_HEX_DIGITS:
                    raise _PrefixRejected("json_unicode_escape_invalid")
                if len(task.value) >= task.max_length * 6:
                    raise _PrefixRejected("string_length_cap")
                task.value += character
                task.unicode_digits += character
                if len(task.unicode_digits) == 4:
                    self._append_decoded_text(
                        task, chr(int(task.unicode_digits, 16))
                    )
                    task.escape_state = ""
                    task.unicode_digits = ""
                return False, ""
            if character == '"':
                if not self.can_close_string(task):
                    raise _PrefixRejected("string_closure_invalid")
                return True, task.decoded_value
            if character == "\\":
                if (
                    len(task.decoded_value) >= task.max_length
                    or len(task.value) >= task.max_length * 6
                ):
                    raise _PrefixRejected("string_length_cap")
                task.value += character
                task.escape_state = "escape"
                return False, ""
            if ord(character) < 0x20:
                raise _PrefixRejected("json_control_character_invalid")
            if len(task.value) >= task.max_length * 6:
                raise _PrefixRejected("string_length_cap")
            self._append_decoded_text(task, character)
            task.value += character
            return False, ""

        if character == '"':
            if not self.can_close_string(task):
                if task.value in self.global_ids:
                    raise _PrefixRejected("duplicate_stable_id")
                raise _PrefixRejected("string_closure_invalid")
            return True, task.value
        if len(task.value) >= task.max_length:
            raise _PrefixRejected("string_length_cap")
        allowed = _STABLE_ID_FIRST if not task.value else _STABLE_ID_REST
        if character not in allowed:
            raise _PrefixRejected("stable_id_character_invalid")
        task.value += character
        return False, ""

    def _on_complete(self, task: _Task, value: str) -> None:
        handler = getattr(self, f"_complete_{task.tag}", None)
        if handler is not None:
            handler(value)

    def _complete_title(self, _: str) -> None:
        self._push(
            _literal(',"layout":{"pattern":'),
            _text(
                "layout_pattern",
                min_length=1,
                max_length=self.limits.max_text_chars,
            ),
        )

    def _complete_layout_pattern(self, _: str) -> None:
        self._push(
            _literal(',"section_stable_ids":['),
            _stable_id(
                "layout_section_id",
                max_length=self.limits.max_stable_id_chars,
            ),
        )

    def _complete_layout_section_id(self, value: str) -> None:
        self._declare("section", value, "layout.section_stable_ids")
        self.layout_section_ids.append(value)
        choices: list[str] = []
        if len(self.layout_section_ids) < self.limits.max_sections:
            choices.append(",")
        choices.append("]")
        self._push(
            _boundary(
                "layout_sections_boundary",
                choices,
                mask_code="section_count_cap",
            )
        )

    def _complete_layout_sections_boundary(self, value: str) -> None:
        if value == ",":
            self._push(
                _stable_id(
                    "layout_section_id",
                    max_length=self.limits.max_stable_id_chars,
                )
            )
            return
        self.current_section_index = 0
        self._push(_literal('},"sections":['))
        self._start_section()

    def _start_section(self) -> None:
        section_id = self.layout_section_ids[self.current_section_index]
        self.current_section_components = []
        self.current_section_use_cases = []
        self._transition(
            "definition_bound",
            "section",
            section_id,
            "sections[*].stable_id",
        )
        self._push(
            _literal('{"stable_id":' + _json_string(section_id) + ',"title":'),
            _text(
                "section_title",
                min_length=1,
                max_length=self.limits.max_text_chars,
            ),
        )

    def _complete_section_title(self, _: str) -> None:
        self._push(
            _literal(',"purpose":'),
            _text(
                "section_purpose",
                min_length=1,
                max_length=self.limits.max_text_chars,
            ),
        )

    def _complete_section_purpose(self, _: str) -> None:
        if len(self.component_owners) >= self.limits.max_components:
            raise _PrefixRejected("component_count_cap")
        self._push(
            _literal(',"component_stable_ids":['),
            _stable_id(
                "section_component_id",
                max_length=self.limits.max_stable_id_chars,
            ),
        )

    def _complete_section_component_id(self, value: str) -> None:
        owner = self.layout_section_ids[self.current_section_index]
        self._declare("component", value, f"owned_by:{owner}")
        self.current_section_components.append(value)
        self.component_owners.append((value, owner))
        choices: list[str] = []
        if len(self.component_owners) < self.limits.max_components:
            choices.append(",")
        choices.append("]")
        self._push(
            _boundary(
                "section_components_boundary",
                choices,
                mask_code="component_count_cap",
            )
        )

    def _complete_section_components_boundary(self, value: str) -> None:
        if value == ",":
            self._push(
                _stable_id(
                    "section_component_id",
                    max_length=self.limits.max_stable_id_chars,
                )
            )
            return
        self._push(
            _literal(',"use_case_ids":['),
            _choice(
                "section_use_case",
                self.approved_use_case_ids,
                mask_code="unapproved_use_case",
            ),
        )

    def _complete_section_use_case(self, value: str) -> None:
        self.current_section_use_cases.append(value)
        remaining = [
            item
            for item in self.approved_use_case_ids
            if item not in self.current_section_use_cases
        ]
        choices: list[str] = []
        if remaining:
            choices.append(",")
